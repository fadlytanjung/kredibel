#!/usr/bin/env python3
"""Write infra/langfuse/.env once: random per-machine credentials for the local Langfuse (ADR-026).

Git ignores the file. Nothing secret is printed: the admin login and the project keys stay in it,
and `make dev-langfuse` reads them from there. Standard library only.
"""

import os
import secrets
import sys
from pathlib import Path

ENV = Path(__file__).resolve().parents[2] / "infra" / "langfuse" / ".env"
USER_EMAIL = "dev@kredibel.local"


def main() -> int:
    if ENV.exists():
        print(f"Using {ENV.relative_to(Path.cwd()) if ENV.is_relative_to(Path.cwd()) else ENV}")
        return 0
    values = {
        "LANGFUSE_POSTGRES_PASSWORD": secrets.token_hex(16),
        "LANGFUSE_CLICKHOUSE_PASSWORD": secrets.token_hex(16),
        "LANGFUSE_REDIS_PASSWORD": secrets.token_hex(16),
        "LANGFUSE_MINIO_PASSWORD": secrets.token_hex(16),
        "LANGFUSE_SALT": secrets.token_hex(16),
        "LANGFUSE_ENCRYPTION_KEY": secrets.token_hex(32),  # 64 hex characters, as Langfuse needs
        "LANGFUSE_NEXTAUTH_SECRET": secrets.token_hex(32),
        "LANGFUSE_PUBLIC_KEY": f"pk-lf-{secrets.token_hex(12)}",
        "LANGFUSE_SECRET_KEY": f"sk-lf-{secrets.token_hex(24)}",
        "LANGFUSE_INIT_USER_EMAIL": USER_EMAIL,
        "LANGFUSE_INIT_USER_PASSWORD": secrets.token_urlsafe(18),
    }
    ENV.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(ENV, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as out:
        out.write("# Local Langfuse credentials (ADR-026). Generated by tools/langfuse/init_env.py.\n")
        out.write("# Per machine; git ignores this file. Delete it with the volumes to start over.\n")
        out.writelines(f"{key}={value}\n" for key, value in values.items())
    print(f"Wrote {ENV}: credentials for this machine (mode 600)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
