#!/usr/bin/env python3
"""Check that no raw styles (hex/rgb/hsl colours, arbitrary Tailwind values, or unauthorized style= props) appear in frontend code.

Design system rules:
- contracts/design/tokens.json is the single source of truth for colours, spacing, radius, and shadows.
- Tailwind utilities generated by `make tokens` must be used instead of raw values.
- Inline style= is only permitted for computed geometry (e.g. charts, bbox overlays) and must be marked with
  /* allow-raw-style: <reason> */ or // allow-raw-style: <reason>.

Acceptance criteria: AC-001-18.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

# Paths/files to exempt from scanning
EXEMPT_FILES = {
    "tokens.css",
    "tailwind-theme.css",
    # Generated from design/mocks/assets/kit.css and icons.py (ADR-019); reviewed at the source.
    "kit.css",
    "icons.generated.ts",
}

# Regex patterns
HEX_COLOR_RE = re.compile(r"(?:\[|\b|['\":\s(,])#(?:[0-9a-fA-F]{3,4}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})\b")
RGB_HSL_RE = re.compile(r"\b(rgb|rgba|hsl|hsla)\(")
ARBITRARY_TW_RE = re.compile(r"(?:[a-zA-Z0-9_-]+-\[[^\]]+\]|\[[0-9]+(?:px|rem|em|%)\]|\[#[0-9a-fA-F]{3,8}\])")
STYLE_PROP_RE = re.compile(r"\bstyle\s*=\s*[{'\"]")

ALLOW_COMMENT_RE = re.compile(r"allow-raw-style")
URL_ANCHOR_RE = re.compile(r"href\s*=\s*['\"]#[a-zA-Z0-9_-]*['\"]|url\(#[^)]+\)")


def check_file(path: Path) -> list[str]:
    violations: list[str] = []
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()

    for idx, line in enumerate(lines, start=1):
        # Skip lines with explicit allowlist comment
        if ALLOW_COMMENT_RE.search(line):
            continue

        # Ignore standard href="#" or SVG url(#id)
        cleaned_line = URL_ANCHOR_RE.sub("", line)

        # 1. Hex color
        hex_match = HEX_COLOR_RE.search(cleaned_line)
        if hex_match:
            val = hex_match.group(0).strip(" [('\":,")
            violations.append(f"{path}:{idx}: raw hex color '{val}' outside tokens (AC-001-18)")

        # 2. RGB/HSL color
        rgb_match = RGB_HSL_RE.search(cleaned_line)
        if rgb_match:
            violations.append(f"{path}:{idx}: raw '{rgb_match.group(0)}' color outside tokens (AC-001-18)")

        # 3. Arbitrary Tailwind value
        tw_match = ARBITRARY_TW_RE.search(cleaned_line)
        if tw_match:
            violations.append(
                f"{path}:{idx}: arbitrary Tailwind value '{tw_match.group(0)}' outside tokens (AC-001-18)"
            )

        # 4. Inline style= prop outside allowlist
        style_match = STYLE_PROP_RE.search(cleaned_line)
        if style_match:
            violations.append(
                f"{path}:{idx}: inline style= prop outside allow-list; use Tailwind or add /* allow-raw-style: <reason> */ (AC-001-18)"
            )

    return violations


def check_no_raw_styles(scan_path: Path) -> list[str]:
    """Scan directory or file for raw style violations."""
    violations: list[str] = []

    if scan_path.is_file():
        if scan_path.name not in EXEMPT_FILES:
            violations.extend(check_file(scan_path))
        return violations

    for ext in ("*.tsx", "*.ts", "*.jsx", "*.js", "*.css", "*.html"):
        for file_path in sorted(scan_path.rglob(ext)):
            # Skip node_modules and dist
            parts = file_path.parts
            if "node_modules" in parts or "dist" in parts or ".storybook" in parts:
                continue
            if file_path.name in EXEMPT_FILES:
                continue

            violations.extend(check_file(file_path))

    return violations


def main() -> int:
    repo_root = Path(__file__).resolve().parents[2]
    frontend_src = repo_root / "frontend" / "src"

    if not frontend_src.exists():
        print(f"Skipping: {frontend_src} does not exist.")
        return 0

    violations = check_no_raw_styles(frontend_src)
    if violations:
        print("ERROR: Found raw styles or unapproved style= props in frontend/src/ (AC-001-18):")
        for v in violations:
            print(f"  {v}")
        print("\nFix: Use token-backed Tailwind classes or mark computed geometry with /* allow-raw-style: <reason> */.")
        return 1

    print("OK: No raw styles in frontend/src/ (AC-001-18).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
