#!/usr/bin/env python3
"""Write the HTML mocks in design/mocks/ from the screen functions in this folder.

    python3 tools/design/mocks/build_mocks.py        # or: make mocks

One function per screen in screens.py and screens_more.py (and brand.py), a shared shell in shell.py,
the dashboard charts in charts.py (sankey.py draws the client and supplier view) and the icon set in
icons.py. Links between mocks make the folder a clickable prototype; design/mocks/assets/proto.js adds
the few behaviours a static page needs (segmented controls, picking a candidate, selecting a row). Styles come only from design/mocks/assets/tokens.css
(generated by `make tokens`) and design/mocks/assets/kit.css. All data is synthetic (docs/18).
Then take the screenshots with `make mock-shots` (tools/design/shoot_mocks.py).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from brand import brand_body  # noqa: E402
from screens import NOTES, SCREENS  # noqa: E402
from screens_more import NOTES_MORE, SAMPLES, SCREENS_MORE  # noqa: E402

SCREENS = {**SCREENS, **SCREENS_MORE}
NOTES = {**NOTES, **NOTES_MORE}
from shell import page  # noqa: E402

ROOT = HERE.parents[2]
MOCKS = ROOT / "design" / "mocks"


def write_index() -> None:
    cards = []
    for slug, (title, _) in SCREENS.items():
        desk = f"../../docs/assets/mocks/{slug}-desktop.png"
        cards.append(f"""
    <li class="index-card">
      <a class="index-shot" href="{slug}.html"><img src="{desk}" alt="" loading="lazy"/></a>
      <div class="index-text">
        <h2 class="type-h3"><a href="{slug}.html">{title}</a></h2>
        <p>{NOTES[slug]}</p>
        <p class="index-sizes"><a href="../../docs/assets/mocks/{slug}-mobile.png">Phone</a>
        <a href="../../docs/assets/mocks/{slug}-tablet.png">Tablet</a>
        <a href="{desk}">Desktop</a></p>
      </div>
    </li>""")
    body = f"""<div class="viewport"><main class="index-page">
  <header class="index-head">
    <img src="../brand/kredibel-logo.svg" alt="Kredibel" height="40"/>
    <h1 class="type-title">Screen mocks</h1>
    <p>High-fidelity, responsive mocks with synthetic data: the demo workspace of docs/18 (Sunrise Coffee Roasters, January to June 2026, scenarios S1 to S4 together).
    Every link, tab and button leads to another mock, so you can click through them like a prototype, starting at the dashboard.
    Resize the window: every mock works from 360 px to 1600 px. The rules are in
    docs/12-design-system.md, the tokens in contracts/design/tokens.json, and the screen specs in docs/11-frontend.md.
    The HTML is generated by tools/design/mocks/ (make mocks).</p>
    <p class="row"><a class="button button-primary" href="dashboard.html">Start the prototype</a><a class="button button-secondary" href="brand.html">Logo and brand</a></p>
  </header>
  <ul class="index-grid">{''.join(cards)}
  </ul>
</main></div>"""
    (MOCKS / "index.html").write_text(page("Screens", body), encoding="utf-8")


def main() -> int:
    for slug, (title, fn) in SCREENS.items():
        html = page(title, fn())
        # In the prototype, filters, tabs and suggestions stay on their own page instead of "#".
        html = re.sub(r'(<a class="(?:chip|tab|month-prev|month-next)"[^>]*?)href="#"', rf'\1href="{slug}.html"', html)
        html = re.sub(r'(<div class="suggested"[^>]*>.*?</div>)', lambda m: m.group(1).replace('href="#"', f'href="{slug}.html"'), html, flags=re.S)
        # Citations open the evidence; any other placeholder stays on its page. Left as "#": the More
        # sheet's close area, search (no search mock yet) and links that leave the app (data-external).
        html = html.replace('class="citation" href="#"', 'class="citation" href="evidence-viewer.html"')
        html = re.sub(r'<a (?![^>]*(?:class="scrim"|search-field|data-external))([^>]*?)href="#"', rf'<a \1href="{slug}.html"', html)
        (MOCKS / f"{slug}.html").write_text(html, encoding="utf-8")
        print("wrote", f"design/mocks/{slug}.html")
    (MOCKS / "brand.html").write_text(page("Logo and brand", brand_body()), encoding="utf-8")
    print("wrote design/mocks/brand.html")
    (MOCKS / "samples").mkdir(exist_ok=True)
    for name, text in SAMPLES.items():
        (MOCKS / "samples" / name).write_text(text, encoding="utf-8")
    print(f"wrote {len(SAMPLES)} extraction samples")
    write_index()
    print("wrote design/mocks/index.html")
    return 0


if __name__ == "__main__":
    sys.exit(main())
