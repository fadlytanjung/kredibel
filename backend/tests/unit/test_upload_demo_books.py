"""The demo upload sends the half-year once plus what each scenario changes (docs/18 §5)."""

import json
from pathlib import Path

from scripts.upload_demo_books import upload_plan


def scenario(root: Path, name: str, files: dict[str, bytes]) -> None:
    folder = root / name / "seed-1"
    folder.mkdir(parents=True)
    for file_name, content in files.items():
        (folder / file_name).write_bytes(content)
    (folder / "truth.json").write_text(json.dumps({"uploadOrder": list(files)}))


def test_the_first_scenario_in_full_then_only_new_names_or_contents(tmp_path):
    scenario(
        tmp_path, "S1", {"statement-02.pdf": b"feb", "statement-03.pdf": b"mar", "inv-1.pdf": b"i1"}
    )
    scenario(
        tmp_path,
        "S2",
        {"statement-02.pdf": b"feb", "statement-03.pdf": b"mar-edited", "inv-1.pdf": b"i1"},
    )
    scenario(
        tmp_path,
        "S3",
        {"statement-02.pdf": b"feb", "statement-02 (1).pdf": b"feb", "inv-1.pdf": b"i1"},
    )

    plan = [(s, p.name) for s, p in upload_plan(tmp_path, ("S1", "S2", "S3"))]

    assert plan == [
        ("S1", "statement-02.pdf"),
        ("S1", "statement-03.pdf"),
        ("S1", "inv-1.pdf"),
        ("S2", "statement-03.pdf"),  # same name, edited content
        ("S3", "statement-02 (1).pdf"),  # same bytes under a new name: the intended exact copy
    ]


def test_a_stopped_upload_resumes_with_what_is_missing(tmp_path):
    scenario(tmp_path, "S1", {"a.pdf": b"a", "b.pdf": b"b"})
    scenario(tmp_path, "S3", {"a (1).pdf": b"a", "c.pdf": b"c"})
    import hashlib

    done = {("a.pdf", hashlib.sha256(b"a").hexdigest())}
    plan = [(s, p.name) for s, p in upload_plan(tmp_path, ("S1", "S3"), already=done)]
    assert plan == [("S1", "b.pdf"), ("S3", "a (1).pdf"), ("S3", "c.pdf")]


def test_the_generated_demo_set_is_the_half_year_plus_ten_scenario_files():
    demo = Path(__file__).resolve().parents[3] / "tools" / "synthetic" / "out" / "demo"
    if not demo.exists():  # generated by `make synth`
        return
    plan = upload_plan(demo)
    assert len(plan) == 81
    assert sum(1 for s, _ in plan if s != "S1") == 10


def test_upload_plan_filters_by_months(tmp_path):
    scenario(
        tmp_path,
        "S1",
        {
            "statement-2026-04.pdf": b"apr",
            "statement-2026-05.pdf": b"may",
            "statement-2026-06.pdf": b"jun",
            "statement-2026-01.pdf": b"jan",
        },
    )
    target_months = {"2026-04", "2026-05", "2026-06"}
    plan = [(s, p.name) for s, p in upload_plan(tmp_path, ("S1",), months=target_months)]
    assert plan == [
        ("S1", "statement-2026-04.pdf"),
        ("S1", "statement-2026-05.pdf"),
        ("S1", "statement-2026-06.pdf"),
    ]

